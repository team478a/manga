function localizeExternalMessage(message: string, locale: AppLocale) {
  const unwrapped = message.replace(
    /^Error invoking remote method '[^']+': Error: /,
    "",
  );
  if (locale === "ja") return unwrapped;
  let localized = unwrapped;
  let translated = false;
  for (const [pattern, replacement] of englishMainMessageReplacements) {
    const next = localized.replace(pattern, replacement);
    if (next !== localized) translated = true;
    localized = next;
  }
  if (!translated && /[\u3040-\u30ff\u3400-\u9fff]/.test(localized))
    return "The operation could not be completed. Review the input and try again.";
  return localized;
}

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [locale, setLocaleState] = React.useState<AppLocale>(storedLocale);
  const localeCode = locale === "ja" ? "ja-JP" : "en-US";
  const setLocale = React.useCallback((next: AppLocale) => {
    setLocaleState(next);
    try {
      localStorage.setItem("mangai.locale", next);
    } catch {
      // 保存できない環境でも現在のセッションでは言語を切り替える。
    }
  }, []);
  React.useEffect(() => {
    document.documentElement.lang = locale;
  }, [locale]);
  const value = React.useMemo<I18nContextValue>(() => {
    const messages = locale === "ja" ? ja : en;
    return {
      locale,
      localeCode,
      setLocale,
      t: (key, values = {}) =>
        Object.entries(values).reduce(
          (message, [name, replacement]) =>
            message.replaceAll(`{${name}}`, String(replacement)),
          messages[key],
        ),
      localizeMessage: (message) => localizeExternalMessage(message, locale),
      formatDateTime: (input) =>
        new Intl.DateTimeFormat(localeCode, {
          dateStyle: "medium",
          timeStyle: "short",
        }).format(new Date(input)),
    };
  }, [locale, localeCode, setLocale]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const value = React.useContext(I18nContext);
  if (!value) throw new Error("I18nProvider is required.");
  return value;
}
